    '''
        Defines an immutable motion plan command in a choreography sequence.

        It defines:

            :attributes:
                | cmd_id - Numeric command identifier byte.
                | payload - Serialized command payload bytes.
                | description - Human-readable explanation of command.
    '''

    cmd_id: int
    payload: bytes
    description: str = ''
